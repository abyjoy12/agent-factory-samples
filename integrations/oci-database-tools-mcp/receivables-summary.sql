SELECT ORG_ID,INVOICE_CURRENCY_CODE,STATUS,COUNT(*) SCHEDULE_COUNT,
 ROUND(SUM(AMOUNT_DUE_REMAINING),2) REMAINING_AMOUNT,
 MIN(DUE_DATE) EARLIEST_DUE_DATE,MAX(DUE_DATE) LATEST_DUE_DATE
FROM APPS.XXAF_FIN_AR_BALANCES_V WHERE AMOUNT_DUE_REMAINING>0
GROUP BY ORG_ID,INVOICE_CURRENCY_CODE,STATUS
ORDER BY REMAINING_AMOUNT DESC FETCH FIRST 15 ROWS ONLY;
