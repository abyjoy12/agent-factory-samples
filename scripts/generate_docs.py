def _json(path: Path, label: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"{path}: cannot read valid {label} JSON: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError(f"{path}: {label} must be an object")
    return value


def _object(value: Any, path: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValueError(f"{path} must be an object")
    return value


def _text(value: Any, path: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{path} must be a non-empty string")
    return value.strip()


def _strings(value: Any, path: str, empty: bool = False) -> tuple[str, ...]:
    if not isinstance(value, list) or (not value and not empty):
        raise ValueError(f"{path} must be {'an' if empty else 'a non-empty'} array of strings")
    return tuple(_text(item, f"{path}[{index}]") for index, item in enumerate(value))


def _artifact(folder: Path, value: Any, path: str) -> str:
    relative = _text(value, path)
    pure = PurePosixPath(relative)
    if pure.is_absolute() or ".." in pure.parts:
        raise ValueError(f"{path} must stay inside the sample folder")
    if not (folder / relative).is_file():
        raise ValueError(f"{path} points to a missing file: {relative}")
    return relative


def _source_url(folder_url: str, path: str) -> str:
    return f"{folder_url.rstrip('/')}/{path}" if folder_url else ""


def load_agent(folder: Path, repository_url: str = "", release_base_url: str = "") -> Agent:
    path = folder / "sample.json"
    sample = _json(path, "sample manifest")
    if sample.get("schemaVersion") != "1.0":
        raise ValueError(f"{path}: schemaVersion must be '1.0'")

    application = _object(sample.get("application"), f"{path}: application")
    application_slug = _text(application.get("slug"), f"{path}: application.slug")
    application_name = _text(application.get("name"), f"{path}: application.name")
    use_case = _object(sample.get("useCase"), f"{path}: useCase")
    use_case_slug = _text(use_case.get("slug"), f"{path}: useCase.slug")
    use_case_name = _text(use_case.get("name"), f"{path}: useCase.name")
    if application_slug != folder.parent.name:
        raise ValueError(f"{path}: application.slug must match parent folder '{folder.parent.name}'")
    if use_case_slug != folder.name:
        raise ValueError(f"{path}: useCase.slug must match folder name '{folder.name}'")

    slug = _text(sample.get("slug"), f"{path}: slug")
    name = _text(sample.get("title"), f"{path}: title")
    description = _text(sample.get("summary"), f"{path}: summary")
    category = _text(sample.get("category"), f"{path}: category")
    version = _text(str(sample.get("version", "")), f"{path}: version")
    platform = _object(sample.get("platform"), f"{path}: platform")
    platform_version = _text(platform.get("applicationVersion"), f"{path}: platform.applicationVersion")
    connection_context = _text(sample.get("connectionContext"), f"{path}: connectionContext")

    memory = _object(sample.get("memory"), f"{path}: memory")
    memory_mode = _text(memory.get("mode"), f"{path}: memory.mode")
    if memory_mode not in {"none", "explicit", "implicit"}:
        raise ValueError(f"{path}: memory.mode must be none, explicit, or implicit")
    memory_description = _text(memory.get("description"), f"{path}: memory.description")
    cross_thread = memory.get("crossThread")
    if not isinstance(cross_thread, bool):
        raise ValueError(f"{path}: memory.crossThread must be a boolean")

    raw_tools = sample.get("tools")
    if not isinstance(raw_tools, list) or not raw_tools:
        raise ValueError(f"{path}: tools must be a non-empty array")
    tools = tuple(
        Tool(
            name=_text(_object(item, f"{path}: tools[{index}]").get("name"), f"{path}: tools[{index}].name"),
            method=_text(item.get("method"), f"{path}: tools[{index}].method").upper(),
            path=_text(item.get("path"), f"{path}: tools[{index}].path"),
            purpose=_text(item.get("purpose"), f"{path}: tools[{index}].purpose"),
        )
        for index, item in enumerate(raw_tools)
    )

    demo = _object(sample.get("demo"), f"{path}: demo")
    raw_sessions = demo.get("sessions")
    if not isinstance(raw_sessions, list) or not raw_sessions:
        raise ValueError(f"{path}: demo.sessions must be a non-empty array")
    sessions: list[DemoSession] = []
    for session_index, item in enumerate(raw_sessions):
        session = _object(item, f"{path}: demo.sessions[{session_index}]")
        raw_steps = session.get("steps")
        if not isinstance(raw_steps, list) or not raw_steps:
            raise ValueError(f"{path}: demo.sessions[{session_index}].steps must be a non-empty array")
        steps = tuple(
            DemoStep(
                speaker=_text(_object(step, "demo step").get("speaker"), f"{path}: demo step speaker"),
                text=_text(step.get("text"), f"{path}: demo step text"),
            )
            for step in raw_steps
        )
        sessions.append(DemoSession(_text(session.get("title"), f"{path}: session title"), steps))

    validation = _object(sample.get("validation"), f"{path}: validation")
    artifacts = _object(sample.get("artifacts"), f"{path}: artifacts")
    workflow_path = _artifact(folder, artifacts.get("workflow"), f"{path}: artifacts.workflow")
    metadata_path = _artifact(folder, artifacts.get("archiveMetadata"), f"{path}: artifacts.archiveMetadata")
    instructions_path = _artifact(folder, artifacts.get("instructions"), f"{path}: artifacts.instructions")
    openapi_path = _artifact(folder, artifacts["openapi"], f"{path}: artifacts.openapi") if artifacts.get("openapi") else ""
    dependency_path = _artifact(folder, artifacts["dependencies"], f"{path}: artifacts.dependencies") if artifacts.get("dependencies") else ""
    if not openapi_path and not dependency_path:
        raise ValueError(f"{path}: artifacts requires openapi or dependencies")
    release_asset = _text(artifacts.get("releaseAsset"), f"{path}: artifacts.releaseAsset")
    if release_asset != f"{slug}.paf":
        raise ValueError(f"{path}: releaseAsset must be '{slug}.paf'")
    workflow = _json(folder / workflow_path, "workflow")
    metadata = _json(folder / metadata_path, "archive metadata")
    if workflow.get("name") != name or str(workflow.get("version", "")) != version:
        raise ValueError(f"{path}: title and version must match workflow.json")
    if metadata.get("applicationVersion") != platform_version:
        raise ValueError(f"{path}: platform version must match archive metadata")

    catalog = _object(sample.get("catalog", {}), f"{path}: catalog")
    vocabulary = _json(Path(__file__).parent / "catalog_taxonomy.json", "catalog taxonomy")
    for field in ("domains", "modules", "useCases", "technicalFeatures"):
        if field in catalog:
            values = _strings(catalog[field], f"{path}: catalog.{field}", empty=field == "technicalFeatures")
            unknown = set(values) - set(vocabulary[field])
            if unknown:
                raise ValueError(f"{path}: unknown catalog.{field} labels: {sorted(unknown)}; update catalog_taxonomy.json intentionally")
    domains = _strings(catalog.get("domains", [category]), f"{path}: catalog.domains")
    modules = _strings(catalog.get("modules", [use_case_name]), f"{path}: catalog.modules")
    functional_use_cases = _strings(catalog.get("useCases", [use_case_name]), f"{path}: catalog.useCases")
    keywords = _strings(catalog.get("keywords", []), f"{path}: catalog.keywords", empty=True)
    features = set(_strings(catalog.get("technicalFeatures", []), f"{path}: catalog.technicalFeatures", empty=True))
    node_features = {
        "SelectSqlQueryNode": "SQL queries", "oracleDatabaseTools": "Database tools",
        "oraclePLSQLExecutor": "PL/SQL tools", "restAPITools": "REST API tools",
        "fileUpload": "Document upload", "readCsv": "CSV input", "parser": "Structured parsing",
        "conditionComponent": "Conditional routing", "currentDateTime": "Current date/time",
        "textCombiner": "Text composition", "mcpServer": "MCP tools",
    }
    for node in workflow.get("data", {}).get("nodes", []):
        feature = node_features.get(node.get("data", {}).get("type"))
        if feature:
            features.add(feature)
    if memory_mode != "none":
        features.add("Agent Memory")
    action_mode = _text(catalog.get("actionMode", "Not classified"), f"{path}: catalog.actionMode")

    relative_folder = f"agents/{application_slug}/{use_case_slug}"
    folder_url = f"{repository_url.rstrip('/')}/{relative_folder}" if repository_url else ""
    return Agent(
        slug=slug,
        application_slug=application_slug,
        application_name=application_name,
        use_case_slug=use_case_slug,
        use_case_name=use_case_name,
        name=name,
        description=description,
        category=category,
        domains=domains, modules=modules, functional_use_cases=functional_use_cases,
        technical_features=tuple(sorted(features)), keywords=keywords, action_mode=action_mode,
        business_question=_text(catalog.get("question", name), f"{path}: catalog.question"),
        display_name=_text(catalog.get("displayName", name), f"{path}: catalog.displayName"),
        version=version,
        platform_version=platform_version,
        connection_context=connection_context,
        memory_mode=memory_mode,
        memory_description=memory_description,
        cross_thread_memory=cross_thread,
        capabilities=_strings(sample.get("capabilities"), f"{path}: capabilities"),
        prerequisites=_strings(sample.get("prerequisites"), f"{path}: prerequisites"),
        tools=tools,
        safety_controls=_strings(sample.get("safetyControls"), f"{path}: safetyControls"),
        setup=_strings(sample.get("setup"), f"{path}: setup"),
        demo_sessions=tuple(sessions),
        expected_outcomes=_strings(demo.get("expectedOutcomes"), f"{path}: demo.expectedOutcomes"),
        validation_date=_text(validation.get("date"), f"{path}: validation.date"),
        validation_environment=_text(validation.get("environment"), f"{path}: validation.environment"),
        validation_status=_text(validation.get("status"), f"{path}: validation.status"),
        validation_notes=_strings(validation.get("notes"), f"{path}: validation.notes", empty=True),
        workflow_path=workflow_path,
        metadata_path=metadata_path,
        instructions_path=instructions_path,
        openapi_path=openapi_path,
        dependency_path=dependency_path,
        release_asset=release_asset,
        folder_url=folder_url,
        readme_url=_source_url(folder_url, "README.md"),
        workflow_url=_source_url(folder_url, workflow_path),
        openapi_url=_source_url(folder_url, openapi_path) if openapi_path else "",
        dependency_url=_source_url(folder_url, dependency_path) if dependency_path else "",
        instructions_url=_source_url(folder_url, instructions_path),
        release_url=f"{release_base_url.rstrip('/')}/{release_asset}" if release_base_url else "",
        page_url=f"agents/{application_slug}/{use_case_slug}/",
    )


def discover_agents(root: Path, repository_url: str = "", release_base_url: str = "") -> list[Agent]:
    agents_root = root / "agents"
    if not agents_root.is_dir():
        raise ValueError(f"{agents_root}: agents directory does not exist")
    folders = (
        use_case
        for application in agents_root.iterdir()
        if application.is_dir() and not application.name.startswith(".")
        for use_case in application.iterdir()
        if use_case.is_dir() and not use_case.name.startswith(".")
        and (use_case / "sample.json").is_file()
    )
    agents = [load_agent(folder, repository_url, release_base_url) for folder in folders]
    if len({a.slug for a in agents}) != len(agents):
        raise ValueError("catalog sample slugs must be unique")
    return sorted(agents, key=lambda agent: (agent.application_name.casefold(), agent.name.casefold()))


def _list(items: tuple[str, ...], ordered: bool = False) -> str:
    tag = "ol" if ordered else "ul"
    return f"<{tag}>" + "".join(f"<li>{html.escape(item)}</li>" for item in items) + f"</{tag}>"


def _link(url: str, label: str) -> str:
    return f'<a href="{html.escape(url, quote=True)}">{html.escape(label)}</a>' if url else f"<span>{html.escape(label)}</span>"


FACETS = (("application", "Application", "application_name"),
          ("domain", "Business domain", "domains"),
          ("usecase", "Functional use case", "functional_use_cases"),
          ("module", "Application module", "modules"),
          ("feature", "Technical feature", "technical_features"))


def _facet_links(key: str, values: tuple[str, ...]) -> str:
    return ', '.join(_link('../../../?' + urlencode({key: value}), value) for value in values)


def _agent_card(a: Agent) -> str:
    tags = ''.join(f'<span>{html.escape(t)}</span>' for t in a.technical_features[:3])
    if len(a.technical_features) > 3:
        tags += f'<span title="{html.escape(", ".join(a.technical_features[3:]), quote=True)}">+{len(a.technical_features)-3} more</span>'
    return (
        f'<article class="card agent-card" data-slug="{html.escape(a.slug, quote=True)}" data-application="{html.escape(a.application_slug, quote=True)}">'
        f'<div class="card-eyebrow"><span class="app-badge">{html.escape(a.application_name)}</span><span class="mode">{html.escape(a.action_mode)}</span></div>'
        f'<h2><a class="agent-link" href="{html.escape(a.page_url, quote=True)}">{html.escape(a.business_question)}</a></h2><p class="card-summary">{html.escape(a.description)}</p>'
        f'<div class="agent-name">{html.escape(a.display_name)}</div>'
        f'<div class="card-domain">{html.escape(" / ".join(a.domains))}</div>'
        f'<div class="use-case-tags">{"".join(f"<span>{html.escape(x)}</span>" for x in a.functional_use_cases)}</div>'
        f'<div class="card-bottom"><div class="feature-tags">{tags}</div><a class="agent-link guide-link" href="{html.escape(a.page_url, quote=True)}" aria-label="Explore {html.escape(a.display_name, quote=True)}">Explore guide <span aria-hidden="true">↗</span></a></div></article>'
    )


