SELECT BUSINESS_UNIT, VENDOR_SETID, VENDOR_ID, UPPER(TRIM(INVOICE_ID)) NORMALIZED_INVOICE_ID,
 TXN_CURRENCY_CD, GROSS_AMT, COUNT(*) CANDIDATE_COUNT, MIN(INVOICE_DT) FIRST_INVOICE_DATE,
 MAX(INVOICE_DT) LAST_INVOICE_DATE, MIN(VOUCHER_ID) EXAMPLE_VOUCHER
FROM PAF_DATA.FSCM_INVOICES
WHERE INVOICE_ID IS NOT NULL
GROUP BY BUSINESS_UNIT,VENDOR_SETID,VENDOR_ID,UPPER(TRIM(INVOICE_ID)),TXN_CURRENCY_CD,GROSS_AMT
HAVING COUNT(*) > 1
ORDER BY CANDIDATE_COUNT DESC,BUSINESS_UNIT,VENDOR_ID,NORMALIZED_INVOICE_ID FETCH FIRST 5 ROWS ONLY;
