-- Fixed SELECT from the official workflow export.
SELECT p.POSITION_NBR,p.POSITION_TITLE,p.BUSINESS_UNIT,p.DEPTID,p.EFF_STATUS,p.MAX_HEAD_COUNT,p.FTE POSITION_FTE,
 NVL(a.ASSIGNMENT_COUNT,0) ASSIGNMENT_COUNT,NVL(a.EMPLOYEE_COUNT,0) DISTINCT_EMPLOYEES_AT_POSITION,
 NVL(a.ASSIGNMENT_FTE,0) ASSIGNMENT_FTE,p.EFFDT POSITION_EFFECTIVE_DATE,
 a.FIRST_ASSIGNMENT_EFFECTIVE_DATE,a.LAST_ASSIGNMENT_EFFECTIVE_DATE
FROM PAF_DATA.HCM_POSITIONS p LEFT JOIN
 (SELECT POSITION_NBR,COUNT(*) ASSIGNMENT_COUNT,COUNT(DISTINCT EMPLOYEE_ID) EMPLOYEE_COUNT,
 SUM(FTE) ASSIGNMENT_FTE,MIN(EFFDT) FIRST_ASSIGNMENT_EFFECTIVE_DATE,MAX(EFFDT) LAST_ASSIGNMENT_EFFECTIVE_DATE
 FROM PAF_DATA.HCM_ASSIGNMENTS WHERE POSITION_NBR IS NOT NULL GROUP BY POSITION_NBR) a
 ON a.POSITION_NBR=p.POSITION_NBR
ORDER BY NVL(a.ASSIGNMENT_COUNT,0),p.POSITION_NBR FETCH FIRST 10 ROWS ONLY;
