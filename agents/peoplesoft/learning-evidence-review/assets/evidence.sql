SELECT e.COURSE_ID,c.COURSE_CODE,c.COURSE_NAME,e.MANDATORY_ENROLLMENT,
 e.ENROLLMENT_STATUS,COUNT(*) ENROLLMENT_COUNT,
 SUM(CASE WHEN e.COMPLETED_DATE IS NOT NULL THEN 1 ELSE 0 END) RECORDED_COMPLETIONS,
 SUM(CASE WHEN e.COMPLETED_DATE IS NULL AND e.TARGET_COMPLETION_DATE < TRUNC(SYSDATE) THEN 1 ELSE 0 END) PAST_TARGET_WITHOUT_COMPLETION,
 MIN(e.TARGET_COMPLETION_DATE) FIRST_TARGET_DATE,MAX(e.TARGET_COMPLETION_DATE) LAST_TARGET_DATE
FROM PAF_DATA.ELM_ENROLLMENTS e LEFT JOIN PAF_DATA.ELM_COURSES c ON c.COURSE_ID=e.COURSE_ID
GROUP BY e.COURSE_ID,c.COURSE_CODE,c.COURSE_NAME,e.MANDATORY_ENROLLMENT,e.ENROLLMENT_STATUS
ORDER BY PAST_TARGET_WITHOUT_COMPLETION DESC,ENROLLMENT_COUNT DESC FETCH FIRST 12 ROWS ONLY;
