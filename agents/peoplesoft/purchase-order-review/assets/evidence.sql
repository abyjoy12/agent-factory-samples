-- Fixed SELECT from the official workflow export.
SELECT p.BUSINESS_UNIT,p.PO_ID,p.PO_DT,p.VENDOR_SETID,p.VENDOR_ID,p.PO_STATUS,p.HOLD_STATUS,
 p.RECV_STATUS,p.MATCH_STATUS_PO,p.APPROVAL_DT,p.CURRENCY_CD,NVL(l.LINE_COUNT,0) LINE_COUNT
FROM PAF_DATA.FSCM_PURCHASE_ORDERS p LEFT JOIN
 (SELECT BUSINESS_UNIT,PO_ID,COUNT(*) LINE_COUNT FROM PAF_DATA.FSCM_PO_LINES GROUP BY BUSINESS_UNIT,PO_ID) l
 ON l.BUSINESS_UNIT=p.BUSINESS_UNIT AND l.PO_ID=p.PO_ID
ORDER BY p.PO_DT DESC NULLS LAST,p.BUSINESS_UNIT,p.PO_ID FETCH FIRST 10 ROWS ONLY;
