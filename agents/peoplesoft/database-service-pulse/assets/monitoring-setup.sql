-- Run as an authorized DBA in the HCM demo PDB only.
-- PAF_DATA is the existing locked, non-login view owner.
-- PAF_AGENT_RO is the existing application demo reader.
GRANT SELECT ON SYS.DBA_TABLESPACE_USAGE_METRICS TO PAF_DATA WITH GRANT OPTION;
GRANT SELECT ON SYS.V_$SESSION TO PAF_DATA WITH GRANT OPTION;
GRANT SELECT ON SYS.V_$CON_SYSMETRIC TO PAF_DATA WITH GRANT OPTION;

CREATE OR REPLACE VIEW PAF_DATA.DEMO_DB_RESOURCE_PULSE AS
 SELECT TABLESPACE_NAME RESOURCE_NAME,USED_SPACE CURRENT_UTILIZATION,
        USED_SPACE MAX_UTILIZATION,TO_CHAR(TABLESPACE_SIZE) LIMIT_VALUE,
        SYSTIMESTAMP OBSERVED_AT
 FROM SYS.DBA_TABLESPACE_USAGE_METRICS
 WHERE TABLESPACE_NAME IN ('SYSTEM','SYSAUX','PSINDEX','PTTBL','PSIMAGE2','GPAPP','HRAPP')
 WITH READ ONLY;

CREATE OR REPLACE VIEW PAF_DATA.DEMO_DB_SESSION_PULSE AS
 SELECT CASE WHEN STATUS='ACTIVE' THEN 'ACTIVE' ELSE 'INACTIVE' END SESSION_STATE,
        COUNT(*) SESSION_COUNT,SYSTIMESTAMP OBSERVED_AT
 FROM SYS.V_$SESSION
 WHERE TYPE='USER' AND CON_ID=TO_NUMBER(SYS_CONTEXT('USERENV','CON_ID'))
 GROUP BY CASE WHEN STATUS='ACTIVE' THEN 'ACTIVE' ELSE 'INACTIVE' END
 WITH READ ONLY;

CREATE OR REPLACE VIEW PAF_DATA.DEMO_DB_METRIC_PULSE AS
 SELECT METRIC_NAME,VALUE METRIC_VALUE,METRIC_UNIT,BEGIN_TIME,END_TIME,
        INTSIZE_CSEC,SYSTIMESTAMP OBSERVED_AT
 FROM SYS.V_$CON_SYSMETRIC
 WHERE METRIC_NAME IN ('Database CPU Time Ratio','Database Wait Time Ratio',
                    'Average Active Sessions','User Transaction Per Sec',
                    'SQL Service Response Time')
 WITH READ ONLY;

GRANT SELECT ON PAF_DATA.DEMO_DB_RESOURCE_PULSE TO PAF_AGENT_RO;
GRANT SELECT ON PAF_DATA.DEMO_DB_SESSION_PULSE TO PAF_AGENT_RO;
GRANT SELECT ON PAF_DATA.DEMO_DB_METRIC_PULSE TO PAF_AGENT_RO;
