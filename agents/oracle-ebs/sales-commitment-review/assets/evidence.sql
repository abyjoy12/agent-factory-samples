SELECT ORDER_NUMBER, HEADER_ID, LINE_ID, LINE_NUMBER, SHIPMENT_NUMBER, ORG_ID,
 ORDERED_ITEM, ORDERED_QUANTITY, SHIPPED_QUANTITY,
 GREATEST(NVL(ORDERED_QUANTITY,0)-NVL(SHIPPED_QUANTITY,0),0) INDICATIVE_UNSHIPPED_QTY,
 CURRENCY_CODE, UNIT_SELLING_PRICE, REQUEST_DATE, SCHEDULE_SHIP_DATE, LINE_STATUS
FROM APPS.XXAF_SCM_SALES_ORDERS_V
 WHERE NVL(HEADER_CANCELLED_FLAG,'N') <> 'Y' AND NVL(LINE_CANCELLED_FLAG,'N') <> 'Y'
 AND NVL(ORDERED_QUANTITY,0)>NVL(SHIPPED_QUANTITY,0) AND NVL(LINE_STATUS,'UNKNOWN')<>'CLOSED'
ORDER BY REQUEST_DATE NULLS LAST,ORDER_NUMBER,LINE_ID FETCH FIRST 5 ROWS ONLY;
