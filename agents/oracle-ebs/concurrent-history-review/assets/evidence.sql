-- Fixed SELECT from the official workflow export.
SELECT SYSTIMESTAMP OBSERVED_AT,REQUEST_ID,PROGRAM_APPLICATION_ID,CONCURRENT_PROGRAM_ID,
 USER_CONCURRENT_PROGRAM_NAME,REQUEST_DATE,REQUESTED_START_DATE,ACTUAL_START_DATE,ACTUAL_COMPLETION_DATE,
 PHASE_CODE,STATUS_CODE,HOLD_FLAG,ORG_ID,
 CASE WHEN ACTUAL_COMPLETION_DATE>=ACTUAL_START_DATE THEN ROUND((ACTUAL_COMPLETION_DATE-ACTUAL_START_DATE)*1440,2) END COMPLETED_ELAPSED_MINUTES
FROM APPS.XXAF_OPS_CONCURRENT_REQUESTS_V
ORDER BY REQUEST_DATE DESC NULLS LAST,REQUEST_ID DESC FETCH FIRST 10 ROWS ONLY;
