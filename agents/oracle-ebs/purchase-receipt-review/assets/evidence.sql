SELECT ORG_ID,PO_NUMBER,PO_HEADER_ID,PO_LINE_ID,LINE_LOCATION_ID,LINE_NUM,SHIPMENT_NUM,
 VENDOR_NUMBER,VENDOR_NAME,INVENTORY_ITEM_ID,SHIP_TO_ORGANIZATION_ID,UNIT_MEAS_LOOKUP_CODE,
 SHIPMENT_QUANTITY,QUANTITY_RECEIVED,SHIPMENT_QUANTITY-QUANTITY_RECEIVED RAW_SHIPMENT_LESS_RECEIVED,
 NEED_BY_DATE,PROMISED_DATE,AUTHORIZATION_STATUS,APPROVED_FLAG,CLOSED_CODE,CURRENCY_CODE
FROM APPS.XXAF_SCM_PURCHASE_ORDERS_V WHERE CANCELLED_FLAG='N'
 AND SHIPMENT_QUANTITY>QUANTITY_RECEIVED
ORDER BY NEED_BY_DATE NULLS LAST,PO_HEADER_ID,PO_LINE_ID,LINE_LOCATION_ID FETCH FIRST 10 ROWS ONLY;
