SELECT w.WORK_ORDER_TYPE,w.WORK_ORDER_NUMBER,w.WORK_ORDER_SUFFIX,w.WORK_ORDER_DESCRIPTION,w.BRANCH_PLANT,
 p.COMPONENT_SEQUENCE,p.OPERATION_SEQUENCE,p.COMPONENT_ITEM_NUMBER,p.COMPONENT_ITEM_CODE,p.COMPONENT_DESCRIPTION,p.COMPONENT_BRANCH,p.UOM,p.REQUIREMENT_SOURCE_ROWS,
 GREATEST(NVL(p.REQUIRED_QUANTITY,0)-NVL(p.ISSUED_QUANTITY,0)-NVL(p.CANCELLED_QUANTITY,0),0) REQUIRED_NOT_ISSUED_QTY_PER_ROW,
 i.INDICATIVE_AVAILABLE_QUANTITY,t.PRIMARY_UOM INVENTORY_UOM
 FROM (SELECT w.* FROM PAF_JDE_API.WORK_ORDERS w WHERE EXISTS
 (SELECT 1 FROM PAF_JDE_API.WORK_ORDER_PARTS p WHERE p.WORK_ORDER_NUMBER=w.WORK_ORDER_NUMBER AND p.WORK_ORDER_TYPE=w.WORK_ORDER_TYPE
 AND NVL(TRIM(p.WORK_ORDER_SUFFIX),'~')=NVL(TRIM(w.WORK_ORDER_SUFFIX),'~')) ORDER BY WORK_ORDER_NUMBER FETCH FIRST 1 ROW ONLY) w
 JOIN (SELECT WORK_ORDER_TYPE,WORK_ORDER_NUMBER,WORK_ORDER_SUFFIX,COMPONENT_SEQUENCE,OPERATION_SEQUENCE,
 COMPONENT_ITEM_NUMBER,COMPONENT_ITEM_CODE,COMPONENT_DESCRIPTION,COMPONENT_BRANCH,UOM,
 REQUIRED_QUANTITY,ISSUED_QUANTITY,CANCELLED_QUANTITY,COUNT(*) REQUIREMENT_SOURCE_ROWS
 FROM PAF_JDE_API.WORK_ORDER_PARTS GROUP BY WORK_ORDER_TYPE,WORK_ORDER_NUMBER,WORK_ORDER_SUFFIX,
 COMPONENT_SEQUENCE,OPERATION_SEQUENCE,COMPONENT_ITEM_NUMBER,COMPONENT_ITEM_CODE,COMPONENT_DESCRIPTION,
 COMPONENT_BRANCH,UOM,REQUIRED_QUANTITY,ISSUED_QUANTITY,CANCELLED_QUANTITY) p ON p.WORK_ORDER_NUMBER=w.WORK_ORDER_NUMBER AND p.WORK_ORDER_TYPE=w.WORK_ORDER_TYPE
 AND NVL(TRIM(p.WORK_ORDER_SUFFIX),'~')=NVL(TRIM(w.WORK_ORDER_SUFFIX),'~')
 LEFT JOIN PAF_JDE_API.BRANCH_INVENTORY i ON i.ITEM_NUMBER=p.COMPONENT_ITEM_NUMBER AND TRIM(i.BRANCH_PLANT)=TRIM(p.COMPONENT_BRANCH)
 LEFT JOIN PAF_JDE_API.ITEMS t ON t.ITEM_NUMBER=p.COMPONENT_ITEM_NUMBER
 ORDER BY p.COMPONENT_SEQUENCE FETCH FIRST 20 ROWS ONLY;
