SELECT ORG_ID,INVOICE_CURRENCY_CODE,PAYMENT_STATUS_FLAG,COUNT(*) INVOICE_COUNT,
 ROUND(SUM(INVOICE_AMOUNT-NVL(AMOUNT_PAID,0)),2) INDICATIVE_UNPAID_AMOUNT,
 MIN(INVOICE_DATE) FIRST_INVOICE_DATE,MAX(INVOICE_DATE) LAST_INVOICE_DATE
 FROM APPS.XXAF_FIN_AP_INVOICES_V
 WHERE ORG_ID=204 AND INVOICE_CURRENCY_CODE='USD' AND CANCELLED_DATE IS NULL AND INVOICE_AMOUNT>NVL(AMOUNT_PAID,0)
 GROUP BY ORG_ID,INVOICE_CURRENCY_CODE,PAYMENT_STATUS_FLAG
 ORDER BY ORG_ID,INVOICE_CURRENCY_CODE,PAYMENT_STATUS_FLAG FETCH FIRST 5 ROWS ONLY;
